import type { CaptionTrackInfo, VideoMetadata } from "../types";
import { getPageWindow } from "../utils/dom";
import type { Json3Payload } from "./cue-builder";

interface YtCaptionTrackRaw {
  baseUrl?: string;
  name?: { simpleText?: string; runs?: Array<{ text?: string }> };
  vssId?: string;
  languageCode?: string;
  kind?: string;
  isTranslatable?: boolean;
}

interface YtPlayerResponse {
  videoDetails?: {
    videoId?: string;
    title?: string;
    author?: string;
    shortDescription?: string;
    keywords?: string[];
  };
  captions?: {
    playerCaptionsTracklistRenderer?: {
      captionTracks?: YtCaptionTrackRaw[];
    };
  };
}

interface YtMoviePlayerElement extends HTMLElement {
  getPlayerResponse?: () => YtPlayerResponse | null;
  getVideoData?: () => { video_id?: string; title?: string; author?: string } | null;
  loadModule?: (moduleName: string) => void;
  setOption?: (moduleName: string, optionName: string, value: unknown) => void;
  getOption?: (moduleName: string, optionName: string) => unknown;
}

type TimedTextListener = (videoId: string, url: string, payload: Json3Payload | null) => void;

const timedTextUrlByVideo = new Map<string, string>();
const timedTextPayloadByVideo = new Map<string, Json3Payload>();
const timedTextListeners = new Set<TimedTextListener>();
let interceptorInstalled = false;

function extractVideoIdFromUrl(urlStr: string): string | null {
  try {
    const u = new URL(urlStr, location.origin);
    return u.searchParams.get("v");
  } catch {
    return null;
  }
}

export function ensureJson3Url(rawUrl: string): string {
  try {
    const u = new URL(rawUrl, location.origin);
    u.searchParams.set("fmt", "json3");
    u.searchParams.delete("tlang");
    return u.toString();
  } catch {
    if (rawUrl.includes("fmt=")) {
      return rawUrl.replace(/fmt=[^&]+/, "fmt=json3");
    }
    return `${rawUrl}${rawUrl.includes("?") ? "&" : "?"}fmt=json3`;
  }
}

function recordTimedTextUrl(rawUrl: string, rawBody?: string): void {
  if (!rawUrl.includes("/api/timedtext")) return;
  const videoId = extractVideoIdFromUrl(rawUrl);
  if (!videoId) return;

  const json3Url = ensureJson3Url(rawUrl);
  timedTextUrlByVideo.set(videoId, json3Url);

  let parsedPayload: Json3Payload | null = null;
  if (rawBody) {
    try {
      const parsed = JSON.parse(rawBody);
      if (parsed && Array.isArray(parsed.events)) {
        parsedPayload = parsed as Json3Payload;
        timedTextPayloadByVideo.set(videoId, parsedPayload);
      }
    } catch {
      // Non-json3 response; we still recorded the signed URL
    }
  }

  for (const listener of timedTextListeners) {
    try {
      listener(videoId, json3Url, parsedPayload);
    } catch {
      // Ignore listener errors
    }
  }
}

/**
 * Installs a lightweight network observer on `fetch` and `XMLHttpRequest`
 * to capture signed `/api/timedtext` URLs (including `pot` tokens) generated by YouTube's player.
 */
export function installTimedTextInterceptor(): void {
  if (interceptorInstalled) return;
  interceptorInstalled = true;

  const pageWin = getPageWindow();

  try {
    const origFetch = pageWin.fetch;
    if (typeof origFetch === "function") {
      pageWin.fetch = async function (input: RequestInfo | URL, init?: RequestInit) {
        const urlStr =
          typeof input === "string"
            ? input
            : input instanceof URL
              ? input.toString()
              : input?.url || "";

        const res = await origFetch.call(this, input, init);
        if (urlStr.includes("/api/timedtext")) {
          try {
            const clone = res.clone();
            clone
              .text()
              .then((text) => recordTimedTextUrl(urlStr, text))
              .catch(() => recordTimedTextUrl(urlStr));
          } catch {
            recordTimedTextUrl(urlStr);
          }
        }
        return res;
      };
    }
  } catch {
    // Ignore if page blocks fetch wrapping
  }

  try {
    const XhrProto = pageWin.XMLHttpRequest?.prototype;
    if (XhrProto) {
      const origOpen = XhrProto.open;
      const origSend = XhrProto.send;

      XhrProto.open = function (
        this: XMLHttpRequest & { _ytppUrl?: string },
        method: string,
        url: string | URL,
        ...rest: unknown[]
      ) {
        this._ytppUrl = typeof url === "string" ? url : url.toString();
        return (origOpen as Function).call(this, method, url, ...rest);
      };

      XhrProto.send = function (
        this: XMLHttpRequest & { _ytppUrl?: string },
        body?: Document | XMLHttpRequestBodyInit | null,
      ) {
        if (this._ytppUrl && this._ytppUrl.includes("/api/timedtext")) {
          const capturedUrl = this._ytppUrl;
          this.addEventListener("load", () => {
            try {
              const text =
                !this.responseType || this.responseType === "text" ? this.responseText : undefined;
              recordTimedTextUrl(capturedUrl, text);
            } catch {
              recordTimedTextUrl(capturedUrl);
            }
          });
        }
        return origSend.call(this, body);
      };
    }
  } catch {
    // Ignore if XHR wrapping fails
  }
}

export function getCurrentVideoId(): string | null {
  try {
    const u = new URL(location.href);
    if (u.pathname === "/watch") {
      return u.searchParams.get("v");
    }
    const shortsMatch = /^\/shorts\/([a-zA-Z0-9_-]+)/.exec(u.pathname);
    if (shortsMatch) {
      return shortsMatch[1];
    }
  } catch {
    // Ignore
  }
  return null;
}

function getPlayerElement(): YtMoviePlayerElement | null {
  return document.getElementById("movie_player") as YtMoviePlayerElement | null;
}

function getActivePlayerResponse(expectedVideoId: string): YtPlayerResponse | null {
  const player = getPlayerElement();
  if (player && typeof player.getPlayerResponse === "function") {
    try {
      const resp = player.getPlayerResponse();
      if (resp?.videoDetails?.videoId === expectedVideoId) {
        return resp;
      }
    } catch {
      // Ignore
    }
  }

  const pageWin = getPageWindow() as unknown as {
    ytInitialPlayerResponse?: YtPlayerResponse;
  };
  const initial = pageWin.ytInitialPlayerResponse;
  if (initial?.videoDetails?.videoId === expectedVideoId) {
    return initial;
  }

  // Also check ytd-watch-flexy playerData if present
  const watchFlexy = document.querySelector("ytd-watch-flexy") as
    | (HTMLElement & { playerData?: YtPlayerResponse })
    | null;
  if (watchFlexy?.playerData?.videoDetails?.videoId === expectedVideoId) {
    return watchFlexy.playerData;
  }

  return null;
}

export function extractVideoMetadata(videoId: string): VideoMetadata {
  const resp = getActivePlayerResponse(videoId);
  const details = resp?.videoDetails;

  const player = getPlayerElement();
  const videoData = player?.getVideoData?.();

  const domTitle =
    document.querySelector("ytd-watch-metadata h1 yt-formatted-string")?.textContent?.trim() ||
    document.title.replace(/\s*-\s*YouTube$/, "").trim();
  const domAuthor =
    document.querySelector("ytd-watch-metadata ytd-channel-name a")?.textContent?.trim() || "";
  const domDesc =
    document.querySelector("#description-inline-expander")?.textContent?.trim() || "";

  return {
    videoId,
    title: details?.title || videoData?.title || domTitle || "",
    author: details?.author || videoData?.author || domAuthor || "",
    description: details?.shortDescription || domDesc || "",
    keywords: details?.keywords,
  };
}

export function extractCaptionTracks(videoId: string): CaptionTrackInfo[] {
  const resp = getActivePlayerResponse(videoId);
  const rawTracks = resp?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
  if (!Array.isArray(rawTracks) || rawTracks.length === 0) {
    return [];
  }

  return rawTracks
    .filter((t) => Boolean(t.baseUrl))
    .map((t) => {
      const name =
        t.name?.simpleText ||
        t.name?.runs?.map((r) => r.text || "").join("") ||
        t.languageCode ||
        "Unknown";
      return {
        baseUrl: t.baseUrl!,
        name,
        vssId: t.vssId || "",
        languageCode: t.languageCode || "en",
        kind: t.kind,
        isTranslatable: t.isTranslatable,
      };
    });
}

/**
 * Picks the best source caption track:
 * 1. Prefer manual (non-ASR) track in original/English/primary language
 * 2. Otherwise fallback to ASR track
 */
export function selectBestCaptionTrack(tracks: CaptionTrackInfo[]): CaptionTrackInfo | null {
  if (tracks.length === 0) return null;

  const manualTracks = tracks.filter((t) => t.kind !== "asr");
  if (manualTracks.length > 0) {
    const enManual = manualTracks.find((t) => /^en\b/i.test(t.languageCode));
    return enManual || manualTracks[0];
  }

  const enAsr = tracks.find((t) => /^en\b/i.test(t.languageCode));
  return enAsr || tracks[0];
}

async function fetchJson3FromUrl(url: string): Promise<Json3Payload | null> {
  try {
    const json3Url = ensureJson3Url(url);
    const res = await fetch(json3Url, { credentials: "same-origin" });
    if (!res.ok) return null;
    const text = await res.text();
    if (!text || !text.trim()) return null;
    const parsed = JSON.parse(text) as Json3Payload;
    if (parsed && Array.isArray(parsed.events) && parsed.events.length > 0) {
      return parsed;
    }
  } catch {
    // Ignore
  }
  return null;
}

/**
 * Fetches the `fmt=json3` subtitle payload for the given video and selected track.
 * Uses direct `baseUrl` fetch first, and falls back to triggering/capturing the player's
 * signed `/api/timedtext` request if YouTube requires a `pot` token.
 */
export async function fetchSubtitleJson3(
  videoId: string,
  track: CaptionTrackInfo,
): Promise<Json3Payload | null> {
  // 1. Check if we already captured a parsed json3 payload for this video
  const cachedPayload = timedTextPayloadByVideo.get(videoId);
  if (cachedPayload && Array.isArray(cachedPayload.events) && cachedPayload.events.length > 0) {
    return cachedPayload;
  }

  // 2. Try direct fetch from track.baseUrl with fmt=json3
  const direct = await fetchJson3FromUrl(track.baseUrl);
  if (direct) {
    return direct;
  }

  // 3. Try using a previously intercepted signed timedtext URL for this video
  const capturedUrl = timedTextUrlByVideo.get(videoId);
  if (capturedUrl) {
    const fromCaptured = await fetchJson3FromUrl(capturedUrl);
    if (fromCaptured) {
      return fromCaptured;
    }
  }

  // 4. Trigger the player's caption module to make a signed request and await interception
  return new Promise<Json3Payload | null>((resolve) => {
    let settled = false;
    const finish = (payload: Json3Payload | null) => {
      if (settled) return;
      settled = true;
      timedTextListeners.delete(onIntercept);
      resolve(payload);
    };

    const timer = setTimeout(() => finish(null), 5000);

    const onIntercept: TimedTextListener = async (vId, signedUrl, inlinePayload) => {
      if (vId !== videoId) return;
      clearTimeout(timer);
      if (inlinePayload && Array.isArray(inlinePayload.events) && inlinePayload.events.length > 0) {
        finish(inlinePayload);
        return;
      }
      const fetched = await fetchJson3FromUrl(signedUrl);
      finish(fetched);
    };

    timedTextListeners.add(onIntercept);

    try {
      const player = getPlayerElement();
      player?.loadModule?.("captions");
      player?.setOption?.("captions", "track", { languageCode: track.languageCode });
    } catch {
      // Ignore
    }
  });
}
